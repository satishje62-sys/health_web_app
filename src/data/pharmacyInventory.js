// Helper function to search medicine in a store's inventory
export function searchMedicineInPharmacy(pharmacyInventory, query) {
  const list = pharmacyInventory && pharmacyInventory.length > 0 ? pharmacyInventory : SAMPLE_PHARMACY_DATABASE;
  if (!query || !query.trim()) return list;

  const q = query.toLowerCase().trim();
  return list.filter((item) => (
    item.name.toLowerCase().includes(q) ||
    item.brandName.toLowerCase().includes(q) ||
    item.genericName.toLowerCase().includes(q) ||
    item.category.toLowerCase().includes(q)
  ));
}
